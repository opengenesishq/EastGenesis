const { app, BrowserWindow, session } = require('electron')
const { writeFileSync } = require('node:fs')
const path = require('node:path')
const [htmlPath, outputPath] = process.argv.slice(2)
app.setPath('userData', path.join(path.dirname(htmlPath), 'user-data'))
app.commandLine.appendSwitch('disable-gpu')
const timeout = setTimeout(() => { console.error('Office role component harness timed out'); app.exit(1) }, 25_000)
app.whenReady().then(async () => {
  session.defaultSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_details, callback) => callback({ cancel: true }))
  const window = new BrowserWindow({ show: false, webPreferences: { nodeIntegration: false, contextIsolation: true, sandbox: true, backgroundThrottling: false } })
  await window.loadFile(htmlPath)
  const checks = await window.webContents.executeJavaScript('window.runOfficeRoleHarness()')
  writeFileSync(outputPath, `${JSON.stringify({ checks, electron: process.versions.electron }, null, 2)}\n`)
  clearTimeout(timeout)
  app.exit(0)
}).catch((error) => { console.error(error); clearTimeout(timeout); app.exit(1) })
