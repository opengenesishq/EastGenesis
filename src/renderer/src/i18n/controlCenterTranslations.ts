export type ControlCenterTranslationKey = keyof typeof CONTROL_CENTER_TRANSLATIONS
type TranslationParams = Record<string, string | number>

export function translateControlCenter(
  language: AppLanguage,
  key: ControlCenterTranslationKey,
  params?: TranslationParams
): string {
  const raw = CONTROL_CENTER_TRANSLATIONS[key][language]
  if (!params) return raw
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match
  )
}

