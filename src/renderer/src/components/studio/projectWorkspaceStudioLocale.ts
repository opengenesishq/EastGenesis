export function currentLanguage(): 'zh' | 'en' {
  return useStore.getState().settings.language
}

export function localized(chinese: string, english: string): string {
  return currentLanguage() === 'en' ? english : chinese
}

function localizedRecord<T extends object>(
  chinese: T,
  english: Readonly<Record<string, unknown>>
): T {
  return new Proxy(chinese, {
    get(target, property, receiver) {
      if (currentLanguage() !== 'en' || typeof property !== 'string') {
        return Reflect.get(target, property, receiver)
      }
      return english[property] ?? Reflect.get(target, property, receiver)
    }
  })
}
